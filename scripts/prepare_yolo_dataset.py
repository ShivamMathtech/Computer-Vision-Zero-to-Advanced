"""Create independent synthetic YOLO splits and validate normalized labels."""

import argparse
import hashlib
import json
from pathlib import Path

import cv2
import numpy as np


def validate(root):
    root = Path(root)
    seen = set()
    counts = {}
    for split in ("train", "val", "test"):
        images = sorted((root / "images" / split).glob("*.png"))
        if not images:
            raise ValueError(f"Missing images: {split}")
        for path in images:
            digest = hashlib.sha256(path.read_bytes()).hexdigest()
            if digest in seen:
                raise ValueError(f"Duplicate image across dataset: {path}")
            seen.add(digest)
            labels = root / "labels" / split / (path.stem + ".txt")
            if not labels.exists():
                raise ValueError(f"Missing labels: {labels}")
            for line in labels.read_text().splitlines():
                values = list(map(float, line.split()))
                if len(values) != 5:
                    raise ValueError(f"Expected class cx cy width height: {labels}")
                cls, cx, cy, w, h = values
                if cls not in (0, 1) or not (
                    0 < w <= 1
                    and 0 < h <= 1
                    and w / 2 <= cx <= 1 - w / 2
                    and h / 2 <= cy <= 1 - h / 2
                ):
                    raise ValueError(f"Invalid normalized box: {labels}")
        counts[split] = len(images)
    return counts


def prepare(root, seed=42):
    root = Path(root)
    if root.exists() and any(root.iterdir()):
        raise ValueError("Choose a new or empty dataset directory.")
    for offset, (split, count) in enumerate((("train", 80), ("val", 20), ("test", 20))):
        rng = np.random.default_rng(seed + offset * 1000)
        for group in ("images", "labels"):
            (root / group / split).mkdir(parents=True, exist_ok=True)
        for i in range(count):
            image = rng.integers(0, 35, (128, 128, 3), dtype="uint8")
            labels = []
            for _ in range(int(rng.integers(1, 4))):
                r = int(rng.integers(8, 19))
                cx, cy = rng.integers(r, 128 - r, size=2)
                cls = int(rng.integers(2))
                color = tuple(int(v) for v in rng.integers(110, 255, size=3))
                if cls == 0:
                    cv2.circle(image, (cx, cy), r, color, -1)
                else:
                    cv2.rectangle(image, (cx - r, cy - r), (cx + r, cy + r), color, -1)
                labels.append(
                    f"{cls} {(cx + 0.5) / 128:.8f} {(cy + 0.5) / 128:.8f} {(2 * r + 1) / 128:.8f} {(2 * r + 1) / 128:.8f}"
                )
            cv2.imwrite(str(root / "images" / split / f"{i:04}.png"), image)
            (root / "labels" / split / f"{i:04}.txt").write_text("\n".join(labels) + "\n")
    (root / "dataset.yaml").write_text(
        f"path: {json.dumps(str(root.resolve()))}\ntrain: images/train\nval: images/val\ntest: images/test\nnames:\n  0: circle\n  1: square\n"
    )
    counts = validate(root)
    (root / "manifest.json").write_text(
        json.dumps(
            {
                "seed": seed,
                "counts": counts,
                "source": "generated by CV Zero; synthetic shapes",
                "license": "MIT",
            },
            indent=2,
        )
    )
    return counts


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--validate-only", action="store_true")
    args = parser.parse_args()
    try:
        print(validate(args.output) if args.validate_only else prepare(args.output, args.seed))
    except ValueError as exc:
        parser.exit(2, f"{exc}\n")
